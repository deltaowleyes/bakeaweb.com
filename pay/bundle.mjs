/* Bundles the studio's site builder into ONE self-contained file for the bake-pay Supabase Edge Function.
   Runs on every studio build (studio/package.json "build"); place.mjs copies it to docs/assets/site-builder.js,
   so https://bakeaweb.com/assets/site-builder.js always matches the live studio's templates. The function loads it
   from there (pay/function/index.ts), so template changes need no redeploy.
   Uses the studio's own Vite (library build), so ?raw imports and JSON work exactly as in the studio.
   The studio code expects a browser, so a few harmless stand-ins (location, localStorage, window) are set first. */
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { writeFileSync, readFileSync, rmSync } from 'node:fs';
import { createRequire } from 'node:module';
const here = dirname(fileURLToPath(import.meta.url)), studio = resolve(here, '../studio');
const { build } = await import(createRequire(resolve(studio, 'package.json')).resolve('vite'));
const stub = resolve(here, 'function/.react-stub.js'), out = resolve(here, 'function/.out');
/* store.js uses React only for the studio UI hook; the builder never calls it */
writeFileSync(stub, 'export function useSyncExternalStore() { throw new Error("not in the builder"); }\nexport default {};\n');
try {
  await build({
    configFile: false, root: studio, logLevel: 'warn',
    resolve: { alias: { react: stub } },
    define: { __BUILT_AT__: JSON.stringify(new Date().toISOString()) },
    build: { outDir: out, emptyOutDir: true, minify: false, sourcemap: false, copyPublicDir: false, cssCodeSplit: false,
      lib: { entry: resolve(here, 'function/build-entry.js'), formats: ['es'], fileName: () => 'site-build.js' } }
  });
  const banner = '/* GENERATED by pay/bundle.mjs from studio/src — do not edit. */\n'
    + 'if (!globalThis.location) globalThis.location = new URL("https://bakeaweb.com/");\n'
    + 'if (!globalThis.localStorage) globalThis.localStorage = { getItem() { return null; }, setItem() {}, removeItem() {} };\n'
    + 'if (!globalThis.window) globalThis.window = globalThis;\n';
  /* one module with no imports: the stand-ins at the top run before any bundled code */
  writeFileSync(resolve(here, 'function/site-build.js'), banner + readFileSync(resolve(out, 'site-build.js'), 'utf8'));
  console.log('Bundled the site builder for bake-pay (pay/function/site-build.js).');
} finally { rmSync(stub, { force: true }); rmSync(out, { recursive: true, force: true }); }
